import type { NoteTable } from '~/utils/notes'

/** 종류 카드: 정의 한 문장 + 핵심 사실 + 출처 */
/** subs: 그 종류 안의 세부 항목 (예: 투영 좌표계 → TM·UTM-K·Web Mercator) */
/** dim: 카드가 다루는 차원 (2D·2.5D·3D) — 같은 주제 안에서 차원이 갈릴 때 */
export type TopicTerm = { name: string; sub: string; dim?: string; def: string; facts: string[]; src: string[]; subs?: { name: string; code?: string; text: string }[] }

export type Dim = '2D' | '2.5D' | '3D'

/** 이어지는 질문: 실제로 받았다는 후기(면접 후기)나 실무에서 부딪힌 문제(실무 함정). 출처 하나씩, 빼려면 배열에서 그 항목만 지운다 */
export type FollowUp = { q: string; a: string; kind: '면접 후기' | '실무 함정'; src: { title: string; url: string } }

export type Topic = {
  /** 주소 #id. 실제 질문이 면접 문서에 있으면 그 번호의 소문자(q001) */
  id: string
  /** notes.ts noteCats의 id (시각화 유형은 카탈로그 categories의 id) */
  cat: string
  /** 중요 표시: 면접 문서(interview.txt)의 실제 질문 번호 */
  real?: string
  /** 중요 표시: 면접 문서에 없는 실제 질문 (직접 받은 것) */
  asked?: string
  /** 1단계: 상위 개념 질문과 정의 */
  what: { q: string; def: string; facts: string[]; src: string[] }
  /** 1단계: 2D·2.5D·3D에서 각각 어떻게 되는지 (여러 차원에 걸친 주제) */
  dims?: { d: Dim; text: string }[]
  dimsSrc?: string[]
  /** 2단계 */
  kindsQ?: string
  terms?: TopicTerm[]
  /** 3단계 */
  diffQ?: string
  table?: NoteTable
  tableSrc?: string[]
  /** 5단계 */
  follow?: FollowUp[]
  points?: string[]
  code?: string
  here?: string
  /** 종류 카드·차이 표를 카탈로그의 서버 도구에서 만든다 (notes.ts) */
  servers?: true
  /** 종류 카드·차이 표를 카탈로그의 도구 종류(toolTypes)에서 만든다 (notes.ts) */
  tools?: true
  /** 겹치는 내용을 먼저 다룬 앞 주제 id → "앞 질문 참고" 링크 */
  see?: string[]
  /** app/note-figs/<fig>.vue */
  fig?: string
  links?: { to: string; label: string }[]
}

