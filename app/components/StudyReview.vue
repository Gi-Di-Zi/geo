    <p>형식 이름을 외우는 데서 한 걸음 더 나아가, 선택 이유와 변환 뒤 확인할 항목을 설명해 보세요.</p>

    <details>
      <summary>1. Shapefile은 .shp 파일 하나만 전달하면 되나요?</summary>
      <p>.shp는 도형, .shx는 도형 위치 색인, .dbf는 속성 표입니다. 같은 이름의 파일들을 함께 보존하고, 좌표계를 설명하는 .prj와 속성 인코딩을 설명하는 .cpg도 확인합니다. 여러 파일을 묶어 전달하려고 ZIP을 많이 사용합니다.</p>
      <p>한글이 깨지면 ZIP 안 파일 이름의 인코딩과 .dbf 속성의 인코딩을 구분해 조사합니다. 원본 설명과 .cpg를 확인하고 실제 한글 속성을 대조하며, 모든 SHP를 UTF-8이나 CP949로 단정하지 않습니다.</p>
    </details>

    <details>
      <summary>2. GeoJSON과 MVT는 둘 다 벡터인데 언제 다르게 쓰나요?</summary>
      <p>GeoJSON은 도형 좌표와 속성을 JSON으로 담아 읽고 다루기 쉽습니다. 작은 데이터를 한 파일로 제공할 때 간단하지만 전체 파일을 읽는 방식은 대용량에서 부담이 됩니다. RFC 7946 좌표는 WGS 84의 경도·위도 순서입니다.</p>
      <p>MVT는 도형을 타일별 정수 격자와 이진 데이터로 담아 보이는 영역만 요청하기 좋습니다. 제작 과정의 단순화·피처 제거·타일 경계 분할 때문에 원본 도형과 달라질 수 있습니다. 정밀한 분석에는 원본을 보존하고, 화면 표시에는 목적에 맞는 타일을 사용합니다.</p>
    </details>

    <details>
      <summary>3. COG는 일반 GeoTIFF와 무엇이 다르고 서버에서는 무엇을 확인하나요?</summary>
      <p>COG는 GeoTIFF 내부를 블록과 축소본, 블록 위치를 찾는 목차로 정리해 필요한 부분만 읽기 좋게 만든 형식입니다. 확장자가 .tif라는 사실만으로 COG라고 판단하지 않고 내부 구조를 확인합니다.</p>
      <p>클라이언트가 HTTP Range로 일부 바이트를 요청하고 서버가 해당 범위를 206 Partial Content로 응답하는지 확인합니다. 다른 출처의 파일을 브라우저에서 읽는 경우에는 CORS도 확인합니다. 파일만 COG로 바꾸어도 브라우저·서버가 부분 읽기를 지원하지 않으면 그 이점을 누리지 못합니다.</p>
    </details>

    <details>
      <summary>4. .gltf와 .glb는 무엇이 다르고 지도에 올릴 때 무엇이 더 필요한가요?</summary>
      <p>둘 다 glTF 모델입니다. .gltf는 JSON 문서이며 버퍼·텍스처를 별도 파일로 참조할 수 있고, .glb는 JSON과 바이너리 데이터를 묶는 컨테이너입니다. 배포할 때는 외부 참조와 상대 경로가 남아 있는지 확인합니다.</p>
      <p>모델이 보인다고 지도 위치까지 정해지는 것은 아닙니다. 원점·축 방향·길이 단위와 배치할 경위도·높이를 확인하고, 필요한 경우 위치 변환을 담은 3D Tiles로 구성합니다.</p>
    </details>

    <details>
      <summary>5. 점군과 삼각형 메시는 어떻게 다른가요?</summary>
      <p>점군은 각각의 위치와 색·반사강도·분류 같은 속성을 가진 점들의 집합입니다. 삼각형 메시는 정점들을 면으로 연결해 표면을 표현합니다. 점의 수가 많다고 면의 연결 관계가 자동으로 생기지는 않습니다.</p>
      <p>LAS·LAZ 점군을 웹에서 보여 주는 일과 점군에서 표면을 재구성하는 일은 별도 작업입니다. 좌표계·색·분류 보존이 필요한지, 표면의 형태가 필요한지에 따라 처리 도구와 출력 형식을 고릅니다.</p>
    </details>

    <details>
      <summary>6. 변환 명령이 성공했고 화면에 보이면 검증이 끝난 건가요?</summary>
      <p>종료 코드와 파일 존재 외에도 입력·출력의 좌표계, 범위, 속성·자료형, 한글, 도형 유효성과 필요한 피처의 보존을 대조해야 합니다. 래스터는 해상도·밴드·NoData·값의 변화, 3D는 위치·축·높이·재질도 확인합니다.</p>
      <p>타일 경계에서 한 피처가 여러 조각이 되면 단순 개수 비교는 오해를 만듭니다. 고유 식별자와 줌별 결과를 비교하고, 단순화·압축·양자화 등 의도한 손실과 예상하지 못한 누락을 구분합니다. 화면 표시용 사본과 분석용 원본의 목적도 구분합니다.</p>
    </details>

    <details>
      <summary>7. 파일로 제공하는 방식과 공간 서비스 방식은 어떻게 고르나요?</summary>
      <p>갱신이 드물고 미리 만든 결과를 보여 주면 정적 파일·타일 제공이 단순합니다. COG·PMTiles처럼 부분 읽기를 활용할 수도 있지만 원본 변경 뒤에는 결과를 다시 만들어야 합니다.</p>
      <p>자주 바뀌는 데이터, 서버의 조건 조회·권한 관리, WMS·WFS 같은 표준 연동이 필요하면 서비스 방식을 검토합니다. 서버 방식은 DB·보안·캐시 운영 부담이 있습니다. WMS의 지도 이미지와 WFS의 도형·속성 응답도 목적이 다르므로 파일 크기만으로 선택하지 않습니다.</p>
